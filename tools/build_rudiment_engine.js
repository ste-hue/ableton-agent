#!/usr/bin/env node
"use strict";

// Build artifact only: Rudiment's six authoritative source scripts remain in
// ste-hue/rudiment. No network fetch, engine rewrite, UI, MIDI renderer or JUCE.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const REVISION = "e9fafb8d970f40fc8c3fd7147d6f550278aa9206";
const VERSION = "0.1.0";
const SOURCES = [
  ["src/engine/core-config.js", "d82e9142597f2f33c9763364c49ba6634cdd0005"],
  ["src/engine/drum-machine-theory-engine.js", "9f359348a045db48dde68304fab62bc48f7c7069"],
  ["src/engine/theory-rudiment-engine.js", "d0c5214500aafb89aad5d68b959875682fa8d294"],
  ["src/engine/fill-engine.js", "c55a19350a74ccb3983314d31d78b34a6d88324b"],
  ["src/engine/arrangement-engine.js", "3f2c3765ce0453bd37313cc1d4cb865cfca5d6f4"],
  ["src/engine/timing-velocity-engine.js", "dbada6686b21de6e37d553390cb440c7c176dca8"],
];
const GOLDEN_PATH = "test/fixtures/golden.json";
const GOLDEN_BLOB = "79131bf35a537c1b7c1e1cf8b528d9040add973c";
const DEFAULT_OUTPUT = path.resolve(__dirname, "../devices/Tembro/code/engines/rudiment");
const DEFAULT_FIXTURE = path.resolve(__dirname, "../devices/Tembro/test/fixtures/rudiment-golden-parity.json");
const hash = (value) => crypto.createHash("sha256").update(value).digest("hex");
const blobHash = (value) => crypto.createHash("sha1").update(Buffer.from("blob " + value.length + "\0")).update(value).digest("hex");
const json = (value) => JSON.stringify(value, null, 2) + "\n";

function requireValue(value, message) {
  if (!value) throw new Error("Rudiment bundle: " + message);
}

function renderBundle(sourceBytes) {
  requireValue(sourceBytes.length === SOURCES.length, "exactly six source files required");
  const chunks = [Buffer.from("// Generated by tools/build_rudiment_engine.js; do not edit.\n// ste-hue/rudiment @ " + REVISION + "\n")];
  let offset = chunks[0].length;
  const sources = [];
  for (let index = 0; index < SOURCES.length; index++) {
    const [relative, expected] = SOURCES[index];
    const bytes = sourceBytes[index];
    requireValue(Buffer.isBuffer(bytes) && blobHash(bytes) === expected, "pinned source mismatch: " + relative);
    const prefix = Buffer.from("\n// Source: " + relative + "\n");
    chunks.push(prefix, bytes, Buffer.from("\n"));
    sources.push({ path: relative, git_blob_sha: expected, sha256: hash(bytes), offset_bytes: offset + prefix.length, size_bytes: bytes.length });
    offset += prefix.length + bytes.length + 1;
  }
  const bundle = Buffer.concat(chunks);
  const manifest = {
    schema: "tembro.engine-bundle.v1", engine: "rudiment", version: VERSION,
    repository: "ste-hue/rudiment", source_revision: REVISION,
    declared_license: "UNLICENSED", minimum_node_major: 18,
    bundle_file: "engine.bundle.js", bundle_sha256: hash(bundle), bundle_bytes: bundle.length,
    sources,
  };
  return { bundle, manifest };
}

function build({ sourceRoot, outputDir = DEFAULT_OUTPUT, fixtureOutput, check = false }) {
  requireValue(typeof sourceRoot === "string" && sourceRoot.length > 0, "sourceRoot is required");
  const root = path.resolve(sourceRoot);
  const sourceBytes = SOURCES.map(([relative]) => fs.readFileSync(path.join(root, relative)));
  const { bundle, manifest } = renderBundle(sourceBytes);
  const files = [
    [path.join(outputDir, "engine.bundle.js"), bundle],
    [path.join(outputDir, "manifest.json"), Buffer.from(json(manifest))],
  ];
  if (fixtureOutput) {
    const fixture = fs.readFileSync(path.join(root, GOLDEN_PATH));
    requireValue(blobHash(fixture) === GOLDEN_BLOB, "pinned golden fixture mismatch");
    const originalGoldens = JSON.parse(fixture.toString("utf8"));
    const parity = {
      schema: "tembro.rudiment-golden-parity.v1", source_revision: REVISION,
      source_fixture: GOLDEN_PATH, source_fixture_git_blob_sha: GOLDEN_BLOB,
      cases: Object.entries(originalGoldens).map(([name, value]) => ({ name, config: value.config, result_sha256: value.hashes.result })),
    };
    files.push([fixtureOutput, Buffer.from(json(parity))]);
  }
  if (check) {
    for (const [file, bytes] of files) {
      requireValue(fs.readFileSync(file).equals(bytes), "generated artifact is stale: " + file);
    }
  } else {
    // Every source and fixture is verified before writing any generated file.
    for (const [file, bytes] of files) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, bytes);
    }
  }
  return manifest;
}

function verify(outputDir = DEFAULT_OUTPUT) {
  const manifestBytes = fs.readFileSync(path.join(outputDir, "manifest.json"));
  const manifest = JSON.parse(manifestBytes.toString("utf8"));
  const bundle = fs.readFileSync(path.join(outputDir, "engine.bundle.js"));
  requireValue(manifest.source_revision === REVISION && manifest.version === VERSION && manifest.engine === "rudiment", "unsupported source identity");
  requireValue(Array.isArray(manifest.sources) && manifest.sources.length === SOURCES.length, "incomplete source manifest");
  const sourceBytes = manifest.sources.map((entry, index) => {
    requireValue(entry.path === SOURCES[index][0] && entry.git_blob_sha === SOURCES[index][1], "source order or pin changed");
    requireValue(Number.isInteger(entry.offset_bytes) && entry.offset_bytes >= 0 && Number.isInteger(entry.size_bytes) && entry.size_bytes > 0 && entry.offset_bytes + entry.size_bytes <= bundle.length, "invalid source byte boundaries");
    return bundle.subarray(entry.offset_bytes, entry.offset_bytes + entry.size_bytes);
  });
  const expected = renderBundle(sourceBytes);
  requireValue(bundle.equals(expected.bundle), "bundle differs from the canonical pinned source composition");
  requireValue(manifestBytes.equals(Buffer.from(json(expected.manifest))), "manifest does not match the pinned bundle");
  return manifest;
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2);
    const value = (flag) => { const index = args.indexOf(flag); return index < 0 ? undefined : args[index + 1]; };
    const known = new Set(["--source-root", "--output-dir", "--fixture-output", "--check"]);
    for (let i = 0; i < args.length; i++) {
      requireValue(known.has(args[i]), "unknown argument: " + args[i]);
      if (args[i] !== "--check") {
        requireValue(args[i + 1] && !args[i + 1].startsWith("--"), "argument value missing");
        i++;
      }
    }
    const sourceRoot = value("--source-root"), outputDir = value("--output-dir") || DEFAULT_OUTPUT;
    const fixtureOutput = value("--fixture-output") || (value("--output-dir") ? undefined : DEFAULT_FIXTURE);
    requireValue(sourceRoot || args.includes("--check"), "use --source-root PATH to build, or --check to verify checked-in artifacts");
    requireValue(sourceRoot || !value("--fixture-output"), "--fixture-output requires --source-root");
    const manifest = sourceRoot ? build({ sourceRoot, outputDir, fixtureOutput, check: args.includes("--check") }) : verify(outputDir);
    console.log(JSON.stringify({ engine: manifest.engine, source_revision: manifest.source_revision, bundle_sha256: manifest.bundle_sha256, checked: args.includes("--check") }));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { build, verify, renderBundle, REVISION, VERSION, SOURCES, DEFAULT_OUTPUT, DEFAULT_FIXTURE };
